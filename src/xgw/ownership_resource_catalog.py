def contract_for_surface(surface, binding, expected_states):
    if type(surface) is not str or surface not in {row[0] for row in ROWS}:
        raise ValueError("SURFACE_UNKNOWN")
    if type(expected_states) is not dict or set(expected_states) != set(DOMAINS):
        raise ValueError("EXPECTED_DOMAINS_REQUIRED")
    # Conservative closure: completeness is unproven, so ALL domains are required,
    # even where the documented direct-effect lower bound is FILES only.
    return ResourceContract(
        binding,
        tuple(
            ResourceRequirement(
                domain, "declared." + surface + "." + domain.lower(), expected_states[domain]
            )
            for domain in DOMAINS
        ),
        completeness="UNKNOWN",
    )
